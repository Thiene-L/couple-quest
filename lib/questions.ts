/** 按日期稳定取题：同一天必定同一题 */
export function questionForDay(dayKey: string): string {
  // 用日期序数而非哈希，保证换题顺序是连续的、不会短期重复
  const days = Math.floor(new Date(`${dayKey}T00:00:00Z`).getTime() / 86400_000);
  const idx = ((days % QUESTIONS.length) + QUESTIONS.length) % QUESTIONS.length;
  return QUESTIONS[idx];
}
